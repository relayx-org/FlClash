/// Continent of a store country code.
///
/// The groups are the primary continent from countries-list, which is what
/// the store uses. Unknown codes are `other` and stay out of the chips.
String continentOfCountryCode(String countryCode) {
  final alpha2 = alpha2CountryCode(countryCode);
  if (alpha2 == null) return 'other';
  return _alpha2ToContinent[alpha2] ?? 'other';
}

/// Alpha-2 form of [countryCode], when the store's table knows it.
String? alpha2CountryCode(String countryCode) {
  final code = countryCode.trim().toUpperCase();
  if (code.length == 2) {
    return _alpha2ToContinent.containsKey(code) ? code : null;
  }
  if (code.length != 3) return null;
  final alpha2 = _alpha3ToAlpha2[code];
  if (alpha2 == null || !_alpha2ToContinent.containsKey(alpha2)) {
    return null;
  }
  return alpha2;
}

/// Regional-indicator flag for a known country code.
String? countryFlagEmoji(String countryCode) {
  final alpha2 = alpha2CountryCode(countryCode);
  if (alpha2 == null) return null;
  return String.fromCharCodes([
    alpha2.codeUnitAt(0) + 127397,
    alpha2.codeUnitAt(1) + 127397,
  ]);
}

const _nativeIpContinentOrder = ['NA', 'SA', 'EU', 'AS', 'OC', 'AF', 'AN'];

List<String> nativeIpContinentsOf(Iterable<String> countryCodes) {
  final present = <String>{};
  for (final code in countryCodes) {
    final continent = continentOfCountryCode(code);
    if (continent != 'other') present.add(continent);
  }
  return [
    for (final continent in _nativeIpContinentOrder)
      if (present.contains(continent)) continent,
  ];
}

